// Bundle the theme backgrounds and fonts into src/styles/theme-assets.js as
// data URLs, so Project Stewardship's themes work offline with nothing fetched at run
// time. Sources and licences: assets/themes/README.md.
// Run: node hermes_dockyard_plugin/desktop/make-theme-assets.mjs
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const assets = join(here, 'assets/themes')
const art = ['cobalt', 'estuary', 'burgundy', 'violet', 'ember', 'neon', 'grove']
const fonts = {
  'space-grotesk': ['space-grotesk-latin-wght-normal.woff2'],
  'jetbrains-mono': ['jetbrains-mono-latin-wght-normal.woff2'],
  'space-mono': ['space-mono-latin-400-normal.woff2', 'space-mono-latin-700-normal.woff2'],
}
const dataUrl = (file, type) => `data:${type};base64,${readFileSync(file).toString('base64')}`
const lines = [
  '// GENERATED by make-theme-assets.mjs from assets/themes (sources and licences:',
  '// assets/themes/README.md). Do not edit; re-run the script.',
  'export const THEME_ART = Object.freeze({',
  ...art.map((id) => `  ${JSON.stringify(id)}: ${JSON.stringify(dataUrl(join(assets, `${id}.avif`), 'image/avif'))},`),
  '})',
  'export const THEME_FONTS = Object.freeze({',
  ...Object.entries(fonts).map(([id, files]) =>
    `  ${JSON.stringify(id)}: [${files.map((file) => JSON.stringify(dataUrl(join(assets, 'fonts', file), 'font/woff2'))).join(', ')}],`),
  '})',
  '',
]
const out = join(here, 'src/styles/theme-assets.js')
writeFileSync(out, lines.join('\n'))
console.log(`wrote ${out} (${Math.round(lines.join('\n').length / 1024)} KB)`)
