// C7 Reports: the pure model the Reports tab reads a saved report with
// (src/lib/report-vocab.js). A report shows as headings, labelled facts,
// lists and a real table, never as raw Markdown, and nothing is dropped:
// every line of the saved text appears somewhere on the page, so the page,
// Copy and Download all say the same things. Older reports (code names, raw
// timestamps) are shown as they were saved, never rewritten.
import { test } from 'node:test'
import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { parseReport, REPORT_TYPES, reportTypeLabel, reportSections, reportHint, reportWhen } from './src/lib/report-vocab.js'

// A report as the backend writes it from 06/10 (plain words).
const NEW = [
  '# atlas-mobile full report',
  '',
  'Generated: 6 Oct 2026, 11:58 UTC',
  'Generated by: sahil',
  '',
  '## Configuration',
  '',
  '- Mission: Ship the mobile client',
  '- Phase: Build',
  '- Lead: octacon',
  '- Members: None',
  '- Autonomy level: 2',
  '- Verification policy: Max open initiatives: 3; Require tests: yes',
  '',
  '## Delivery',
  '',
  '- Backlog: 3',
  '- In progress: 1',
  '',
  '| Ref | Work item | Status | Assignee |',
  '| --- | --- | --- | --- |',
  '| ATL-1 | Fix the \\| pipe and \\` tick | In progress | octacon |',
  '| ATL-2 | Write notes | Backlog | Unassigned |',
  '',
  '## Risks and decisions',
  '',
  '- Pending initiatives: 1',
  '- Blocked work items: 0',
  '- Unacknowledged alerts: 0',
  '',
  '- Decision: INIT-3 Tidy the checklist (medium risk)',
  '',
  '## Recent activity',
  '',
  '- 6 Oct 2026, 11:58 UTC — Approval requested · INIT-3 · by System',
  '- 6 Oct 2026, 11:50 UTC — Work assigned · ATL-1 · by sahil',
  '',
].join('\n')

// A report saved before 06/10: shown exactly as saved.
const OLD = [
  '# payments-relaunch full report',
  '',
  'Generated: 2026-10-05T09:12:44.120931+00:00',
  'Generated by: sahil',
  '',
  '## Configuration',
  '',
  '- Verification policy: {"require_tests": true}',
  '',
  '| Ref | Work item | Status | Assignee |',
  '| --- | --- | --- | --- |',
  '| PAY-4 | Retry queue | in_progress | octacon |',
  '',
  '## Recent activity',
  '',
  '- 2026-10-05T09:10:01+00:00: initiative.approved INIT-2 by sahil',
].join('\n')

// The Unicode report the Phase 4 download test uses (phase4-host.mjs).
const UNICODE = [
  '# Executive report — payments-relaunch',
  '',
  'Mission: Ship retry-safe payments ✅ without weakening release gates.',
  'Généré par Quan · café review included.',
  '',
  '## Delivery',
  '',
  '- In progress: 2',
  '- Blocked: 1',
  '',
].join('\n')

const headings = (doc) => doc.blocks.filter((block) => block.kind === 'heading').map((block) => block.text)
const blockAfter = (doc, heading, kind) => {
  const start = doc.blocks.findIndex((block) => block.kind === 'heading' && block.text === heading)
  return doc.blocks.slice(start + 1).find((block) => block.kind === kind || block.kind === 'heading')
}
// How many saved lines the model shows (the table's --- line is layout, not text).
const shownLines = (doc) => (doc.title ? 1 : 0) + (doc.generated ? 1 : 0) + (doc.generatedBy ? 1 : 0)
  + doc.blocks.reduce((sum, block) => sum + (block.kind === 'list' ? block.items.length : block.kind === 'table' ? 1 + block.rows.length : 1), 0)
const savedLines = (markdown) => markdown.split('\n').filter((line) => line.trim() && !/^\|(\s*:?-{3,}:?\s*\|)+$/.test(line.trim())).length

test('a new report reads as a title, the generated line, sections, facts, a table and a list', () => {
  const doc = parseReport(NEW)
  assert.equal(doc.title, 'atlas-mobile full report')
  assert.equal(doc.generated, '6 Oct 2026, 11:58 UTC')
  assert.equal(doc.generatedBy, 'sahil')
  assert.deepEqual(headings(doc), ['Configuration', 'Delivery', 'Risks and decisions', 'Recent activity'])
  const settings = blockAfter(doc, 'Configuration', 'list')
  assert.deepEqual(settings.items.map((item) => item.label), ['Mission', 'Phase', 'Lead', 'Members', 'Autonomy level', 'Verification policy'])
  assert.equal(settings.items[5].value, 'Max open initiatives: 3; Require tests: yes', 'the first ": " splits label from value')
  const table = doc.blocks.find((block) => block.kind === 'table')
  assert.deepEqual(table.head, ['Ref', 'Work item', 'Status', 'Assignee'])
  assert.deepEqual(table.rows, [['ATL-1', 'Fix the | pipe and ` tick', 'In progress', 'octacon'], ['ATL-2', 'Write notes', 'Backlog', 'Unassigned']], 'escaped pipes and ticks are unescaped; the --- line is not a row')
  const activity = blockAfter(doc, 'Recent activity', 'list')
  assert.deepEqual(activity.items.map((item) => item.label ?? null), [null, null], 'a timestamped line is a plain list item, not a fact')
  assert.equal(activity.items[0].text, '6 Oct 2026, 11:58 UTC — Approval requested · INIT-3 · by System')
  const decisions = doc.blocks.filter((block) => block.kind === 'list')[3]
  assert.deepEqual(decisions.items.map((item) => [item.label, item.value]), [['Decision', 'INIT-3 Tidy the checklist (medium risk)']])
})

test('nothing is dropped: every saved line shows somewhere', () => {
  for (const [name, markdown] of [['new', NEW], ['old', OLD], ['unicode', UNICODE]]) {
    assert.equal(shownLines(parseReport(markdown)), savedLines(markdown), name)
  }
})

test('an older report is shown as it was saved, code names included', () => {
  const doc = parseReport(OLD)
  assert.equal(doc.generated, '2026-10-05T09:12:44.120931+00:00')
  assert.equal(doc.blocks.find((block) => block.kind === 'list').items[0].value, '{"require_tests": true}')
  assert.deepEqual(doc.blocks.find((block) => block.kind === 'table').rows, [['PAY-4', 'Retry queue', 'in_progress', 'octacon']])
  const activity = doc.blocks.filter((block) => block.kind === 'list').at(-1)
  assert.deepEqual(activity.items, [{ text: '2026-10-05T09:10:01+00:00: initiative.approved INIT-2 by sahil' }])
})

test('Unicode text, plain lines and odd input', () => {
  const doc = parseReport(UNICODE)
  assert.equal(doc.title, 'Executive report — payments-relaunch')
  assert.deepEqual(doc.blocks.filter((block) => block.kind === 'text').map((block) => block.text), [
    'Mission: Ship retry-safe payments ✅ without weakening release gates.', 'Généré par Quan · café review included.',
  ], 'lines outside a list stay plain text')
  assert.deepEqual(parseReport(''), { title: '', generated: '', generatedBy: '', blocks: [] })
  assert.deepEqual(parseReport(null).blocks, [])
  const crlf = parseReport('# T\r\n\r\n## A\r\n- One: 1\r\n# Later\r\n| x | y |\r\n| 1 | 2 |')
  assert.equal(crlf.title, 'T')
  assert.deepEqual(headings(crlf), ['A', 'Later'], 'a second "# " line is a section heading')
  assert.deepEqual(crlf.blocks.at(-1), { kind: 'table', head: ['x', 'y'], rows: [['1', '2']] }, 'a table without a --- line still parses')
})

test('the four report types are the backend\'s, with the select\'s words', () => {
  const service = readFileSync(fileURLToPath(new URL('../../src/hermes_project_stewardship/persistence/dockyard_service.py', import.meta.url)), 'utf8')
  assert.match(service, /if report_type not in \{"executive", "delivery", "risk", "full"\}:/, 'the backend still accepts exactly these four')
  assert.deepEqual(REPORT_TYPES.map((type) => type.value), ['executive', 'delivery', 'risk', 'full'])
  assert.deepEqual(REPORT_TYPES.map((type) => type.label), ['Executive summary', 'Delivery report', 'Risk and decisions', 'Full project report'])
  assert.equal(reportTypeLabel('risk'), 'Risk and decisions')
  assert.equal(reportTypeLabel('quarterly_review'), 'Quarterly review', 'an unknown type still reads as words')
})

test('each type lists the sections the backend writes (the browser test checks them on real reports)', () => {
  assert.deepEqual(reportSections('executive', true), ['Configuration', 'Delivery', 'Risks and decisions', 'Recent activity'])
  assert.deepEqual(reportSections('executive', false), ['Configuration', 'Delivery', 'Risks and decisions'])
  assert.deepEqual(reportSections('delivery', true), ['Configuration', 'Delivery', 'Recent activity'])
  assert.deepEqual(reportSections('risk', true), ['Configuration', 'Risks and decisions'], 'risk never includes activity')
  assert.deepEqual(reportSections('full', true), ['Configuration', 'Delivery', 'Risks and decisions', 'Recent activity'])
  assert.equal(reportHint('executive', true), 'Sections: Configuration · Delivery · Risks and decisions · Recent activity')
  assert.equal(reportHint('delivery', false), 'Sections: Configuration · Delivery, with the work list')
  assert.equal(reportHint('full', true), 'Sections: Configuration · Delivery, with the work list · Risks and decisions · Recent activity')
  assert.equal(reportHint('risk', true), 'Sections: Configuration · Risks and decisions. Risk reports never include recent activity.')
})

test('dates read as day, month, year and time in the person\'s own time zone', () => {
  assert.equal(reportWhen('2026-10-06T11:58:01+00:00', 'Europe/London'), '6 Oct 2026, 12:58')
  assert.equal(reportWhen('2026-01-09T08:05:00Z', 'Europe/London'), '9 Jan 2026, 08:05')
  assert.equal(reportWhen('not a date'), '')
  assert.equal(reportWhen(''), '')
})
