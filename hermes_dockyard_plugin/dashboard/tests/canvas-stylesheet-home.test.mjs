// The canvas stylesheet has exactly ONE written home.
//
// dashboard/src/workflow-canvas-css.ts is that home. Its text is published to
// two surfaces that cannot read each other's files:
//   - the Dashboard bundle, through `npm run build` (appended to dist/style.css)
//   - the Desktop plugin, as the generated sibling desktop/workflow-canvas-css.js
//
// A second hand-maintained copy is exactly the drift that caused the 2026-09-22
// render regression, so this test fails if any published copy is stale — i.e.
// if someone edits a published file, or edits the source and forgets to build.
import assert from 'node:assert/strict'
import { createRequire } from 'node:module'
import { readFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { test } from 'node:test'

const HERE = dirname(fileURLToPath(import.meta.url))
const DASHBOARD = join(HERE, '..')
const PLUGIN = join(DASHBOARD, '..')
const require = createRequire(join(DASHBOARD, 'package.json'))

const SOURCE = join(DASHBOARD, 'src', 'workflow-canvas-css.ts')
const PUBLISHED_DASHBOARD = join(DASHBOARD, 'dist', 'style.css')
const PUBLISHED_DESKTOP = join(PLUGIN, 'desktop', 'workflow-canvas-css.js')

/** Compile the single source with esbuild and read its exported value, so the
 *  comparison is against the module's own value (never a retyped copy). */
async function sourceCss() {
  const esbuild = require('esbuild')
  const built = await esbuild.build({
    entryPoints: [SOURCE], bundle: true, format: 'esm', write: false, target: 'es2022',
  })
  const mod = await import(
    'data:text/javascript;base64,' + Buffer.from(built.outputFiles[0].text).toString('base64')
  )
  return mod.WORKFLOW_CANVAS_CSS
}

test('canvas stylesheet: the published copies are the single source, byte for byte', async () => {
  const source = await sourceCss()
  assert.ok(source.length > 1000, 'the source module must actually export the canvas CSS')

  // 1) The Desktop sibling is the generated module the plugin imports.
  const desktop = readFileSync(PUBLISHED_DESKTOP, 'utf8')
  assert.match(desktop, /^\/\/ GENERATED by dashboard\/build\.mjs/,
    'desktop/workflow-canvas-css.js must be generated, not hand-edited')
  const m = desktop.match(/^export default (.*);$/m)
  assert.ok(m, 'the Desktop sibling must export a default string')
  assert.equal(JSON.parse(m[1]), source,
    'desktop/workflow-canvas-css.js is STALE — run `npm run build` in dashboard/')

  // 2) The Dashboard bundle carries the same text (rules appended to style.css).
  const bundle = readFileSync(PUBLISHED_DASHBOARD, 'utf8')
  assert.ok(bundle.includes(source.trim()),
    'dist/style.css is STALE — it must end with the canvas stylesheet from the single source')

  // 3) The single home is the ONLY written copy of the canvas's own rules: no
  //    hand-maintained duplicate of the node/shape/edge styling may reappear in
  //    the Dashboard stylesheet. (`.dy-wf-progress*` stays legitimately shared:
  //    the milestone row in app.ts uses the same bar, so its rules carry both
  //    carriers in one declaration.)
  const base = readFileSync(join(DASHBOARD, 'src', 'style.css'), 'utf8')
  for (const cls of ['.dy-wf-node', '.dy-wf-shape', '.dy-wf-svg', '.dy-wf-edge']) {
    assert.ok(!base.includes(cls),
      `src/style.css must not re-declare ${cls} — the canvas rules live in workflow-canvas-css.ts`)
  }

  // 4) The palette is declared ONCE. Each purpose/status token must appear
  //    exactly once in the source, so no surface can drift to its own value.
  for (const token of [
    '--dy-wf-purpose-task-fill', '--dy-wf-purpose-gate-fill',
    '--dy-wf-purpose-branch-fill', '--dy-wf-purpose-loop-fill',
    '--dy-wf-status-done', '--dy-wf-status-working',
    '--dy-wf-status-blocked', '--dy-wf-status-pending',
  ]) {
    const decls = source.match(new RegExp(`\\${token}:`, 'g')) ?? []
    assert.equal(decls.length, 1, `${token} must be declared exactly once in the single home`)
  }

  // 4b) The planning canvas (v6 composition) lives in the same single home: its
  //     palette is declared once per theme (light on the carrier, dark under the
  //     Desktop theme attribute), and its rules are the only written copy.
  for (const token of [
    '--dy-pc-kind-evidence', '--dy-pc-kind-claim', '--dy-pc-kind-question',
    '--dy-pc-kind-decision', '--dy-pc-kind-plan_block', '--dy-pc-kind-note',
    '--dy-pc-kind-link', '--dy-pc-kind-media',
    '--dy-edge-plan-supports', '--dy-edge-plan-contradicts',
    '--dy-edge-plan-derived_from', '--dy-edge-plan-clarifies',
    '--dy-edge-plan-implements', '--dy-edge-plan-raises_question',
  ]) {
    const decls = source.match(new RegExp(`\\${token}:`, 'g')) ?? []
    assert.equal(decls.length, 2,
      `${token} must be declared exactly twice in the single home (light carrier + dark override), got ${decls.length}`)
  }
  for (const cls of ['.dy-pc-obj', '.dy-pc-stage', '.dy-pc-world', '.dy-pc-svg']) {
    assert.ok(!base.includes(cls),
      `src/style.css must not re-declare ${cls} — the planning canvas rules live in workflow-canvas-css.ts`)
  }

  // 5) The Desktop source module wires the generated sibling into the plugin —
  //    the committed bundle intentionally contains no relative import.
  const desktopSource = readFileSync(join(PLUGIN, 'desktop', 'src', 'runtime', 'context.js'), 'utf8')
  assert.match(desktopSource, /import workflowCanvasCss from ['"]\.\.\/\.\.\/workflow-canvas-css\.js['"]/,
    'desktop/src/runtime/context.js must import the generated sibling')
  assert.match(desktopSource, /useStylesheet\(['"]dy-wf-stylesheet['"], ['"]dyWfStylesheet['"], workflowCanvasCss\)/,
    'desktop/src/runtime/context.js must install the canvas stylesheet')
  const shipped = readFileSync(join(PLUGIN, 'desktop', 'plugin.js'), 'utf8')
  assert.match(shipped, /useStylesheet\(["']dy-wf-stylesheet["'], ["']dyWfStylesheet["'], workflow_canvas_css_default\)/,
    'desktop/plugin.js must install the inlined canvas stylesheet')
  const inlined = shipped.match(/^var workflow_canvas_css_default = (`[^`]*`);$/m)
  assert.ok(inlined, 'desktop/plugin.js must inline the generated canvas stylesheet')
  // Test-only: read the template literal's value (the shipped file has no eval).
  assert.equal(new Function(`return ${inlined[1]}`)(), source,
    'desktop/plugin.js inlines a STALE canvas stylesheet — rebuild desktop/plugin.js')

  // 6) ...and the surface that renders the canvas carries the scope class the
  //    stylesheet is scoped to.
  const canvasSrc = readFileSync(join(DASHBOARD, 'src', 'workflow-canvas.ts'), 'utf8')
  assert.match(canvasSrc, /host\.className = 'dy-wf dy-wf-scope'/,
    'the canvas mount host must carry the scope class the stylesheet is scoped to')
  assert.ok(!source.includes('.dy-root'),
    'the canvas stylesheet must not depend on a .dy-root ancestor the Desktop surface never renders')
})
