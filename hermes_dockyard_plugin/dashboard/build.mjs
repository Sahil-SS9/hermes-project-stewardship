import { build } from 'esbuild';
import { writeFileSync, mkdirSync, readFileSync, statSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

// cor-008: anchor every path to this script's directory so a wrong-cwd
// invocation can never silently "build" into the wrong place.
const dir = dirname(fileURLToPath(import.meta.url));
const PLUGIN_DIR = join(dir, '..'); // hermes_dockyard_plugin/
const DESKTOP_SIBLING = join(PLUGIN_DIR, 'desktop', 'workflow-canvas-css.js');

mkdirSync(join(dir, 'dist'), { recursive: true });

await build({
  entryPoints: [join(dir, 'src/index.ts')],
  bundle: true,
  outfile: join(dir, 'dist/index.js'),
  format: 'iife',
  target: 'es2022',
  minify: false,
  sourcemap: false,
  external: ['react'], // host provides React via SDK
});

// ---- single home for the canvas stylesheet --------------------------------
// src/workflow-canvas-css.ts is the one written source of the workflow-canvas
// rules and its palette. Its text is read here (by executing the module, so
// the emitted string is the module's own value — never a re-typed copy) and
// published to the two places that need it:
//   1. dist/style.css   — the Dashboard bundle (rules appended after style.css)
//   2. desktop/workflow-canvas-css.js — the sibling module desktop/plugin.js
//      imports (the Desktop runtime loader refuses anything that is not the
//      SDK or a sibling beside plugin.js, so this is the only legal seam).
const cssSrc = join(dir, 'src', 'style.css');
if (!statSync(cssSrc).isFile()) {
  throw new Error(`missing source stylesheet: ${cssSrc}`);
}
const baseCss = readFileSync(cssSrc, 'utf8');

const canvasModule = join(dir, 'src', 'workflow-canvas-css.ts');
if (!statSync(canvasModule).isFile()) {
  throw new Error(`missing canvas stylesheet module: ${canvasModule}`);
}
// Compile the module with the repo's own esbuild and import the result, so the
// published CSS is literally the module's own export value — never re-typed
// here, and independent of Node's TS-stripping support.
const compiled = await build({
  entryPoints: [canvasModule],
  bundle: true,
  format: 'esm',
  write: false,
  target: 'es2022',
});
const canvasCss = (await import(
  'data:text/javascript;base64,' + Buffer.from(compiled.outputFiles[0].text).toString('base64')
)).WORKFLOW_CANVAS_CSS;
if (typeof canvasCss !== 'string' || canvasCss.length === 0) {
  throw new Error('workflow-canvas-css.ts did not export a non-empty WORKFLOW_CANVAS_CSS');
}
if (canvasCss.includes('`')) {
  throw new Error('WORKFLOW_CANVAS_CSS contains a backtick — check the module template literal');
}

writeFileSync(join(dir, 'dist', 'style.css'), baseCss.replace(/\s*$/, '\n') + '\n' + canvasCss);

// The Desktop sibling: a plain ESM module, no imports, no evaluation tricks.
// `export default` a string is the whole contract.
writeFileSync(
  DESKTOP_SIBLING,
  '// GENERATED by dashboard/build.mjs from dashboard/src/workflow-canvas-css.ts\n'
  + '// Do not edit by hand — the generated file is asserted byte-identical in tests.\n'
  + 'export default ' + JSON.stringify(canvasCss) + ';\n',
);

const meta = {
  name: 'hermes-dockyard',
  builtFrom: [
    'src/index.ts', 'src/app.ts', 'src/api.ts',
    'src/style.css', 'src/workflow-canvas-css.ts',
  ],
};
writeFileSync('dist/build-meta.json', JSON.stringify(meta, null, 2) + '\n');

for (const f of [join(dir, 'dist', 'index.js'), join(dir, 'dist', 'style.css'), DESKTOP_SIBLING]) {
  const size = statSync(f).size;
  if (size === 0) throw new Error(`empty build output: ${f}`);
  console.log(`${f.replace(dir + '/', '').replace(PLUGIN_DIR + '/', '')}: ${size} bytes`);
}
