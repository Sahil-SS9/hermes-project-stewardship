// Generate a runtime-safe sibling module from the pinned lucide-static package.
// The Hermes Desktop loader allows sibling imports, not npm runtime imports.
// Source SVGs: lucide-static v1.47.0 (ISC). This is a curated subset.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const dir = dirname(fileURLToPath(import.meta.url));
const iconsDir = join(dir, '..', 'node_modules', 'lucide-static', 'icons');
const output = join(dir, '..', '..', 'desktop', 'lucide-icons.js');
const names = [
  'activity', 'arrow-up-right', 'bell', 'bug', 'chevron-down',
  'chevron-right', 'circle-check', 'clock-3', 'eye', 'file-text',
  'folder-kanban', 'folder-open', 'folders', 'layout-dashboard',
  'list-checks', 'message-square', 'pencil', 'rotate-cw', 'search',
  'shield-alert', 'square-check-big', 'triangle-alert', 'users',
  'workflow', 'zap',
];
const tags = new Set(['path', 'circle', 'rect', 'line', 'polyline', 'polygon', 'ellipse']);
const attribute = (name) => name.replace(/-([a-z])/g, (_, letter) => letter.toUpperCase());
const icons = {};
for (const name of names) {
  const svg = readFileSync(join(iconsDir, `${name}.svg`), 'utf8');
  if (!svg.includes('@license lucide-static v1.47.0 - ISC') || /<g[\s>]/.test(svg)) {
    throw new Error(`Unexpected Lucide source format: ${name}`);
  }
  const nodes = [];
  for (const match of svg.matchAll(/<(path|circle|rect|line|polyline|polygon|ellipse)\b([^>]*?)\s*\/>/gs)) {
    const tag = match[1];
    if (!tags.has(tag)) throw new Error(`Unsupported Lucide tag ${tag}`);
    const attrs = {};
    for (const prop of match[2].matchAll(/([a-z][a-z0-9-]*)="([^"]*)"/g)) {
      attrs[attribute(prop[1])] = prop[2];
    }
    nodes.push([tag, attrs]);
  }
  if (nodes.length === 0) throw new Error(`Lucide icon has no elements: ${name}`);
  icons[name] = nodes;
}
const generated = '// GENERATED by dashboard/scripts/generate-lucide-icons.mjs\n'
  + '// Lucide icons (lucide-static v1.47.0), ISC licence: https://lucide.dev/license\n'
  + '// Source is the pinned npm package; do not edit by hand.\n'
  + `export const LUCIDE_ICON_NODES = ${JSON.stringify(icons, null, 2)};\n`;
if (process.argv.includes('--check')) {
  if (readFileSync(output, 'utf8') !== generated) throw new Error('Lucide sibling module is stale; regenerate it');
  console.log(`Lucide module matches pinned source: ${names.length} icons`);
} else {
  writeFileSync(output, generated);
  console.log(`Generated ${names.length} Lucide icons: ${output}`);
}
